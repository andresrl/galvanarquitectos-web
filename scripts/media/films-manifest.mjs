// Writes app/data/films.generated.ts from public/video/films (scripts/media/build_films.sh): duration, frame, sources
// with their size and a content version per film, so a re-encoded film never survives the 30-day media cache.
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, statSync, writeFileSync } from 'node:fs'

const dir = 'public/video/films', url = name => `/video/films/${name}`
const ids = ['reel-2026', 'the-house', 'villa-paris', 'la-resina-six', 'villa-soal', 'villa-pareja']
const probe = file => JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration:stream=codec_type,width,height', '-of', 'json', file]))
const media = {}
for (const id of ids) {
 const files = [`${id}-1080.mp4`, `${id}-1080.webm`, `${id}-720.mp4`, `${id}-720.webm`, `${id}-preview.mp4`, `${id}-preview.webm`, `${id}-poster-1920.avif`, `${id}-poster-960.avif`, `${id}-poster.jpg`]
 if (id === 'reel-2026') files.push(`${id}-hero.mp4`, `${id}-hero.webm`, `${id}-hero-720.mp4`, `${id}-hero-720.webm`)
 const missing = files.filter(f => !existsSync(`${dir}/${f}`))
 if (missing.length) throw new Error(`${id}: missing ${missing.join(', ')}`)
 const hash = createHash('sha256')
 for (const f of files) hash.update(readFileSync(`${dir}/${f}`))
 const v = hash.digest('hex').slice(0, 10), src = f => `${url(f)}?v=${v}`, bytes = f => statSync(`${dir}/${f}`).size
 const full = probe(`${dir}/${id}-1080.mp4`), video = full.streams.find(s => s.codec_type === 'video')
 const source = q => ({ mp4: src(`${id}-${q}.mp4`), webm: src(`${id}-${q}.webm`), mp4Bytes: bytes(`${id}-${q}.mp4`), webmBytes: bytes(`${id}-${q}.webm`) })
 media[id] = {
  duration: Math.round(Number(full.format.duration) * 100) / 100, width: video.width, height: video.height,
  audio: full.streams.some(s => s.codec_type === 'audio'),
  sources: { 1080: source('1080'), 720: source('720') },
  preview: { mp4: src(`${id}-preview.mp4`), webm: src(`${id}-preview.webm`) },
  ...(id === 'reel-2026' ? { hero: { mp4: src(`${id}-hero.mp4`), webm: src(`${id}-hero.webm`), mobileMp4: src(`${id}-hero-720.mp4`), mobileWebm: src(`${id}-hero-720.webm`) } } : {}),
  poster: { src: src(`${id}-poster-1920.avif`), small: src(`${id}-poster-960.avif`), jpg: src(`${id}-poster.jpg`) }
 }
 console.log(`  ${id}: ${media[id].duration}s · 1080 mp4 ${(bytes(`${id}-1080.mp4`) / 1e6).toFixed(1)} MB, webm ${(bytes(`${id}-1080.webm`) / 1e6).toFixed(1)} MB · 720 mp4 ${(bytes(`${id}-720.mp4`) / 1e6).toFixed(1)} MB, webm ${(bytes(`${id}-720.webm`) / 1e6).toFixed(1)} MB · preview ${(bytes(`${id}-preview.mp4`) / 1e6).toFixed(2)} MB`)
}
writeFileSync('app/data/films.generated.ts', '// Generated by scripts/media/films-manifest.mjs (scripts/media/build_films.sh). Do not edit.\n'
 + 'export type FilmSource = { mp4: string; webm: string; mp4Bytes: number; webmBytes: number }\n'
 + 'export type FilmMedia = { duration: number; width: number; height: number; audio: boolean; sources: Record<\'1080\' | \'720\', FilmSource>; preview: { mp4: string; webm: string }; hero?: { mp4: string; webm: string; mobileMp4: string; mobileWebm: string }; poster: { src: string; small: string; jpg: string } }\n'
 + 'export const filmMedia: Record<string, FilmMedia> = ' + JSON.stringify(media, null, 1) + '\n')
